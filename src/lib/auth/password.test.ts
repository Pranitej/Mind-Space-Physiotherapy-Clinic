import { execFile } from "node:child_process";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { afterEach, beforeAll, describe, expect, it, vi } from "vitest";
import { hashPassword, verifyPassword } from "./password";

const PASSWORD = "correct horse battery staple";
const HASH_FORMAT = /^scrypt:32768:8:1:([A-Za-z0-9_-]+):([A-Za-z0-9_-]+)$/;
const HASH_SCRIPT = fileURLToPath(new URL("../../../scripts/hash-password.mjs", import.meta.url));
const execFileAsync = promisify(execFile);

// scrypt is deliberately slow (~100 ms per hash), so hash once and reuse.
let stored: string;
beforeAll(async () => {
  stored = await hashPassword(PASSWORD);
});

afterEach(() => {
  vi.unstubAllEnvs();
});

/** Replaces one character of the given `:`-separated field with a different base64url character. */
function tamper(hash: string, field: number): string {
  const parts = hash.split(":");
  const value = parts[field]!;
  // Change a character in the middle: the last base64 character can carry only padding bits.
  const index = Math.floor(value.length / 2);
  const replacement = value[index] === "A" ? "B" : "A";
  parts[field] = value.slice(0, index) + replacement + value.slice(index + 1);
  return parts.join(":");
}

describe("hashPassword", () => {
  it("produces scrypt:<N>:<r>:<p>:<salt>:<hash> with a 16-byte salt and 64-byte key", () => {
    const match = HASH_FORMAT.exec(stored);
    expect(match).not.toBeNull();
    expect(Buffer.from(match![1]!, "base64url")).toHaveLength(16);
    expect(Buffer.from(match![2]!, "base64url")).toHaveLength(64);
  });

  it("uses a fresh random salt for every hash", async () => {
    const second = await hashPassword(PASSWORD);
    expect(second).not.toBe(stored);
    expect(await verifyPassword(PASSWORD, second)).toBe(true);
  });

  it("is accepted by the ADMIN_PASSWORD_HASH validation in src/lib/env.ts", async () => {
    vi.stubEnv("MONGODB_URI", "mongodb://localhost:27017/test");
    vi.stubEnv("SESSION_SECRET", "s".repeat(48));
    vi.stubEnv("ADMIN_PASSWORD_HASH", stored);

    const { getServerEnv } = await import("@/lib/env");
    expect(getServerEnv().ADMIN_PASSWORD_HASH).toBe(stored);
  });
});

describe("verifyPassword", () => {
  it("accepts the correct password", async () => {
    expect(await verifyPassword(PASSWORD, stored)).toBe(true);
  });

  it.each(["wrong password", "", "Correct horse battery staple", `${PASSWORD} `])(
    "rejects a wrong password (%j)",
    async (attempt) => {
      expect(await verifyPassword(attempt, stored)).toBe(false);
    },
  );

  it("rejects a hash whose derived key was tampered with", async () => {
    expect(await verifyPassword(PASSWORD, tamper(stored, 5))).toBe(false);
  });

  it("rejects a hash whose salt was tampered with", async () => {
    expect(await verifyPassword(PASSWORD, tamper(stored, 4))).toBe(false);
  });

  it("rejects a hash whose cost parameters were changed", async () => {
    expect(await verifyPassword(PASSWORD, stored.replace("scrypt:32768:", "scrypt:16384:"))).toBe(false);
  });

  it.each([
    "",
    "not-a-hash",
    "scrypt",
    "scrypt:32768:8:1:c2FsdA",
    "scrypt:32768:8:1:c2FsdA:aGFzaA:extra",
    "bcrypt:32768:8:1:c2FsdA:aGFzaA",
    "scrypt:abc:8:1:c2FsdA:aGFzaA",
    "scrypt:32768:8.5:1:c2FsdA:aGFzaA",
    "scrypt:32768:8:1:c2FsdA:",
    "$2b$10$abcdefghijklmnopqrstuuMRnqbP6KkQhJBPd6RKyzXm.mCq2bWWu",
  ])("returns false for a malformed stored hash (%j)", async (malformed) => {
    expect(await verifyPassword(PASSWORD, malformed)).toBe(false);
  });

  // A mistyped ADMIN_PASSWORD_HASH must fail closed instead of turning every login into a 500.
  it.each(["scrypt:3:8:1", "scrypt:0:8:1", "scrypt:2097152:8:1", "scrypt:32768:0:1", "scrypt:32768:8:0"])(
    "returns false (rather than throwing) for invalid scrypt parameters (%s)",
    async (params) => {
      const [, , , , salt, key] = stored.split(":");
      expect(await verifyPassword(PASSWORD, `${params}:${salt}:${key}`)).toBe(false);
    },
  );
});

describe("compatibility with scripts/hash-password.mjs", () => {
  async function runHashScript(password: string) {
    return execFileAsync(process.execPath, [HASH_SCRIPT, password]);
  }

  it("verifies hashes generated by the CLI script", async () => {
    const { stdout } = await runHashScript(PASSWORD);
    const generated = stdout.trim();

    expect(generated).toMatch(HASH_FORMAT);
    expect(await verifyPassword(PASSWORD, generated)).toBe(true);
    expect(await verifyPassword("wrong password", generated)).toBe(false);
  }, 20_000);

  it("refuses to hash passwords shorter than 12 characters", async () => {
    await expect(runHashScript("short")).rejects.toMatchObject({ code: 1 });
  }, 20_000);
});
